import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'], headless: 'new' });
const p = await b.newPage(); await p.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true });
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto('http://localhost:8099/index.html',{waitUntil:'networkidle0'}); await p.evaluate(()=>localStorage.clear()); await p.reload({waitUntil:'networkidle0'});
const click=(q)=>p.evaluate((s)=>document.querySelector(s).click(),q);
const setf=(n,v)=>p.evaluate((n,v)=>{const e=document.querySelector('#dlg [name='+n+']'); if(e.type==='checkbox')e.checked=v; else e.value=v;},n,v);
const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m); if(!c)process.exitCode=1;};
const txt=()=>p.evaluate(()=>document.getElementById('main').innerText);
ok(/Belum ada yang perlu diperhatikan|Mulai/.test(await txt()),'Aplikasi baru kosong (tanpa data palsu)');
await click('#nav [data-v=more]'); await click('[data-a=nav][data-to=bantuan]'); await click('[data-a=demoOn]');
await click('#nav [data-v=rumah]'); await click('[data-a=nav][data-to=perawatan]');
await click('[data-a=planOpen]'); await click('[data-a=planEdit]'); await setf('name','Servis AC ruang tamu (milik saya)'); await click('#fok');
await click('#nav [data-v=more]'); await click('[data-a=nav][data-to=bantuan]'); await click('[data-a=demoOff]');
await click('#nav [data-v=rumah]'); await click('[data-a=nav][data-to=perawatan]');
ok(/milik saya/.test(await txt()),'Data contoh yang saya edit tetap ada setelah "Hapus data contoh"');
ok(!/Kuras toren air/.test(await txt()),'Data contoh yang tidak disentuh terhapus');
await click('#nav [data-v=more]'); await click('[data-a=nav][data-to=tagihan]'); await click('[data-a=billTpl]');
await setf('b0',true); await setf('b1',true); await setf('dueDay','15'); await click('#fok');
const t=await txt(); ok(/Listrik PLN/.test(t)&&/Internet/.test(t),'Template tagihan menambah item');
console.log('ERR',JSON.stringify(errs)); await b.close();
